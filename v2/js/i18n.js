// Current language, persisted in localStorage.
window.I18N_LANG_KEY = "mvdl-lang";

window.I18N_getLang = function () {
  try {
    var saved = localStorage.getItem(window.I18N_LANG_KEY);
    if (saved && window.I18N[saved]) return saved;
  } catch (e) {}
  return "en";
};

window.I18N_apply = function (lang) {
  var dict = window.I18N[lang] || window.I18N.en;
  var fallback = window.I18N.en;

  document.documentElement.setAttribute("lang", lang);

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var key = el.getAttribute("data-i18n");
    var val = dict[key] !== undefined ? dict[key] : fallback[key];
    if (val !== undefined) el.textContent = val;
  });

  document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-html");
    var val = dict[key] !== undefined ? dict[key] : fallback[key];
    if (val !== undefined) el.innerHTML = val;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-placeholder");
    var val = dict[key] !== undefined ? dict[key] : fallback[key];
    if (val !== undefined) el.setAttribute("placeholder", val);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-aria");
    var val = dict[key] !== undefined ? dict[key] : fallback[key];
    if (val !== undefined) el.setAttribute("aria-label", val);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-alt");
    var val = dict[key] !== undefined ? dict[key] : fallback[key];
    if (val !== undefined) el.setAttribute("alt", val);
  });

  if (dict["meta.title"]) document.title = dict["meta.title"];

  // Sync all toggle buttons (desktop + mobile overlay).
  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    var code = (btn.getAttribute("data-lang") || btn.textContent || "").trim().toLowerCase();
    btn.classList.toggle("active", code === lang);
  });

  try { localStorage.setItem(window.I18N_LANG_KEY, lang); } catch (e) {}

  // Notify JS-rendered widgets (e.g. circular gallery) so they can re-translate.
  try { document.dispatchEvent(new CustomEvent("mvdl:lang", { detail: { lang: lang } })); } catch (e) {}
};
